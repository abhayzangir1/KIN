  public computeApprovalDigest(toolName: string, runId?: string, params?: Record<string, any>): string {
    const canonical = params ? canonicalJson(params) : '';
    return crypto
      .createHash('sha256')
      .update(`${toolName}:${runId || '*'}:${canonical}`)
      .digest('hex');
  }

  public hasApprovalToken(token: string): boolean {
    const entry = this.validApprovalTokens.get(token);
    if (!entry) return false;
    if (Date.now() > entry.expiresAt) {
      this.validApprovalTokens.delete(token);
      return false;
    }
    return true;
  }

  /**
   * Registers a single-use authorization token generated by operator approval.
   */
  public registerApprovalToken(
    token: string,
    toolName: string,
    ttlMs: number = 300000,
    runId?: string,
    paramsOrDigest?: Record<string, any> | string
  ): void {
    let paramDigest: string;
    if (typeof paramsOrDigest === 'string') {
      paramDigest = paramsOrDigest;
    } else if (paramsOrDigest && typeof paramsOrDigest === 'object' && Object.keys(paramsOrDigest).length > 0) {
      paramDigest = this.computeApprovalDigest(toolName, runId || '*', paramsOrDigest);
    } else {
      paramDigest = '*';
    }

    this.validApprovalTokens.set(token, {
      toolName,
      runId,
      paramDigest,
      expiresAt: Date.now() + ttlMs,
    });
  }

  /**
   * Consumes a single-use authorization token.
   */
  public consumeApprovalToken(
    token: string,
    toolName: string,
    runId?: string,
    paramsOrDigest?: Record<string, any> | string
  ): boolean {
    const entry = this.validApprovalTokens.get(token);
    if (!entry) return false;

    if (Date.now() > entry.expiresAt) {
      this.validApprovalTokens.delete(token);
      return false;
    }

    if (entry.toolName !== toolName && entry.toolName !== '*') {
      return false;
    }

    if (entry.runId && runId && entry.runId !== '*' && entry.runId !== runId) {
      return false;
    }

    if (!entry.paramDigest) {
      return false;
    }

    if (entry.paramDigest !== '*') {
      let candidateDigest: string | undefined;
      if (typeof paramsOrDigest === 'string') {
        candidateDigest = paramsOrDigest;
      } else if (paramsOrDigest && typeof paramsOrDigest === 'object') {
        candidateDigest = this.computeApprovalDigest(toolName, entry.runId || '*', paramsOrDigest);
      } else {
        candidateDigest = this.computeApprovalDigest(toolName, entry.runId || '*', {});
      }
      if (!candidateDigest || candidateDigest !== entry.paramDigest) {
        return false;
      }
    }

    this.validApprovalTokens.delete(token);
    return true;
  }

